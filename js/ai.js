// SafeHer AI — server-backed situation assessment.
// No local/mock risk score is used. Analysis requires a configured server-side
// AI provider; failure is reported honestly and never triggers SOS automatically.
"use strict";

async function analyzeSituation() {
    const input = document.getElementById("userInput");
    const consent = document.getElementById("aiConsent");
    if (!input || !input.value.trim()) {
        alert("Please describe your situation.");
        return;
    }
    if (!consent?.checked) {
        alert("Please read and accept the AI-provider privacy notice before submitting your description.");
        return;
    }

    const description = input.value.trim();
    if (description.length > 2000) {
        alert("Please shorten your description to 2,000 characters or fewer.");
        return;
    }

    showLoader(true);
    const analyzeButton = document.getElementById("analyzeBtn");
    if (analyzeButton) analyzeButton.disabled = true;

    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 25000);

    try {
        const endpoint = window.SAFEHER_AI_API || "/api/analyze";
        const response = await fetch(endpoint, {
            method: "POST",
            credentials: "same-origin",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ text: description }),
            signal: controller.signal
        });
        const data = await response.json().catch(() => ({}));
        if (!response.ok || !data.ok || !data.assessment) {
            throw new Error(data.error || "AI analysis is unavailable. Use the emergency controls directly if you need help.");
        }

        const assessment = data.assessment;
        const result = {
            level: assessment.urgency,
            summary: assessment.summary,
            recommendations: assessment.recommendations,
            immediateDanger: assessment.immediateDanger,
            model: data.model || "configured AI model",
            method: "server-backed AI assessment"
        };
        updateUI(result);
        if (typeof updateAssistantStatus === "function") {
            updateAssistantStatus(assessment.immediateDanger
                ? "The AI assessment suggests possible immediate danger. It has not activated SOS. Use the emergency controls if you need help."
                : "AI assessment completed. Review the recommendations and use your judgement.");
        }
        if (typeof saveHistory === "function") saveHistory(description, result);
        if (typeof speak === "function") {
            speak(assessment.immediateDanger
                ? "The assessment suggests possible immediate danger. Please review the guidance and use emergency controls if needed."
                : "Your situation assessment is ready. Please review the recommendations.");
        }
    } catch (error) {
        console.error("SafeHer AI assessment unavailable:", error.message);
        const riskLevel = document.getElementById("riskLevel");
        const summary = document.getElementById("riskScoreText");
        const confidence = document.getElementById("confidenceText");
        const list = document.getElementById("recommendationList");
        if (riskLevel) riskLevel.textContent = "Assessment unavailable";
        if (summary) summary.textContent = error.name === "AbortError"
            ? "The request timed out. No assessment was made."
            : error.message;
        if (confidence) confidence.textContent = "No local or simulated result is substituted when the AI service fails.";
        if (list) {
            list.replaceChildren();
            const li = document.createElement("li");
            li.textContent = "If you need help now, use the emergency call or trusted-contact controls directly.";
            list.appendChild(li);
        }
        if (typeof updateAssistantStatus === "function") updateAssistantStatus("AI analysis is unavailable. Emergency controls remain available.");
    } finally {
        clearTimeout(timeoutId);
        showLoader(false);
        if (analyzeButton) analyzeButton.disabled = false;
    }
}

function updateUI(result) {
    const labels = {
        immediate: "Potential immediate concern",
        elevated: "Potential concern",
        unclear: "Needs more context"
    };
    const riskLevel = document.getElementById("riskLevel");
    const summary = document.getElementById("riskScoreText");
    const confidence = document.getElementById("confidenceText");
    if (riskLevel) riskLevel.textContent = labels[result.level] || "Assessment complete";
    if (summary) summary.textContent = result.summary;
    if (confidence) confidence.textContent =
        `Generated by ${result.model}. AI guidance may be incomplete and cannot verify a threat or guarantee safety.`;

    const list = document.getElementById("recommendationList");
    if (list) {
        list.replaceChildren();
        for (const recommendation of result.recommendations || []) {
            const li = document.createElement("li");
            li.textContent = String(recommendation);
            list.appendChild(li);
        }
    }
}

function showLoader(show) {
    document.getElementById("loader")?.classList.toggle("hidden", !show);
}

document.addEventListener("DOMContentLoaded", () => {
    document.getElementById("analyzeBtn")?.addEventListener("click", analyzeSituation);
});

window.SafeHer = window.SafeHer || {};
window.SafeHer.analyzeSituation = analyzeSituation;
